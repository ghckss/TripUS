import { createWriteStream } from 'node:fs';
import { mkdir, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { dirname, resolve } from 'node:path';
import { Readable } from 'node:stream';
import { pipeline } from 'node:stream/promises';
import { spawn } from 'node:child_process';
import { createInterface } from 'node:readline';

const CITY_SOURCE_URL = 'https://download.geonames.org/export/dump/cities15000.zip';
const ALTERNATE_NAMES_SOURCE_URL = 'https://download.geonames.org/export/dump/alternateNamesV2.zip';
const MAX_CITIES_PER_COUNTRY = 50;
const outputPath = resolve('src/modules/places/infrastructure/city-catalog.generated.ts');

async function download(url, filename) {
  const destination = resolve(tmpdir(), filename);
  const response = await fetch(url);
  if (!response.ok || !response.body) throw new Error(`Download failed (${response.status}): ${url}`);
  await pipeline(Readable.fromWeb(response.body), createWriteStream(destination));
  return destination;
}

function zipLines(zipPath, filename) {
  const child = spawn('unzip', ['-p', zipPath, filename], { stdio: ['ignore', 'pipe', 'inherit'] });
  child.on('error', (error) => { throw error; });
  return createInterface({ input: child.stdout, crlfDelay: Infinity });
}

function firstHangulName(alternateNames) {
  return alternateNames.split(',').find((name) => /^[\p{Script=Hangul}\s·-]+$/u.test(name)) ?? null;
}

function compactKoreanCityName(name) {
  if (!name) return null;
  const compact = name.replace(/\s*(?:특별시|광역시|특별자치시|시)$/u, '');
  return compact.length >= 2 ? compact : name;
}

async function loadCities(zipPath) {
  const byCountry = new Map();
  for await (const line of zipLines(zipPath, 'cities15000.txt')) {
    const columns = line.split('\t');
    const countryCode = columns[8];
    const population = Number(columns[14] ?? 0);
    if (!countryCode) continue;
    const city = {
      id: columns[0],
      countryCode,
      name: columns[1],
      fallbackKoreanName: firstHangulName(columns[3] ?? ''),
      latitude: Number(columns[4]),
      longitude: Number(columns[5]),
      population,
    };
    const cities = byCountry.get(countryCode) ?? [];
    cities.push(city);
    byCountry.set(countryCode, cities);
  }

  return [...byCountry.values()]
    .flatMap((cities) => cities
      .sort((left, right) => right.population - left.population || left.name.localeCompare(right.name))
      .slice(0, MAX_CITIES_PER_COUNTRY));
}

async function loadPreferredKoreanNames(zipPath, cityIds) {
  const names = new Map();
  for await (const line of zipLines(zipPath, 'alternateNamesV2.txt')) {
    const columns = line.split('\t');
    const cityId = columns[1];
    if (columns[2] !== 'ko' || !cityId || !cityIds.has(cityId)) continue;
    if (columns[7] === '1') continue;
    const candidate = {
      name: columns[3],
      score: columns[5] === '1' ? 3 : columns[4] === '1' ? 2 : 1,
    };
    const current = names.get(cityId);
    if (
      !current
      || candidate.score > current.score
      || (current.score === 2 && candidate.score === 1 && current.name.startsWith(candidate.name))
    ) names.set(cityId, candidate);
  }
  return names;
}

const citiesZip = process.argv[2] ?? await download(CITY_SOURCE_URL, 'tripus-cities15000.zip');
const alternateNamesZip = process.argv[3] ?? await download(ALTERNATE_NAMES_SOURCE_URL, 'tripus-alternateNamesV2.zip');
const cities = await loadCities(citiesZip);
const koreanNames = await loadPreferredKoreanNames(alternateNamesZip, new Set(cities.map((city) => city.id)));
const rows = cities
  .map((city) => [
    city.id,
    city.countryCode,
    city.name,
    compactKoreanCityName(koreanNames.get(city.id)?.name ?? city.fallbackKoreanName),
    city.latitude,
    city.longitude,
    city.population,
  ])
  .sort((left, right) => left[1].localeCompare(right[1]) || right[6] - left[6]);

const source = `// Generated by scripts/generate-city-catalog.mjs from GeoNames cities15000 and alternateNamesV2.\n`
  + `// GeoNames data is licensed under CC BY 4.0: https://www.geonames.org/\n`
  + `export type CityCatalogRow = readonly [id: string, countryCode: string, name: string, koreanName: string | null, latitude: number, longitude: number, population: number];\n\n`
  + `export const CITY_CATALOG: readonly CityCatalogRow[] = ${JSON.stringify(rows)};\n`;

await mkdir(dirname(outputPath), { recursive: true });
await writeFile(outputPath, source);
console.log(`Generated ${rows.length} cities at ${outputPath}`);
